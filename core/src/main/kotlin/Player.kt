package ru.triplethall.mushroomhunt

/**
 * Состояние игрока в текущей игровой сессии.
 *
 * Здесь собраны данные, которые относятся именно к игроку: здоровье,
 * доступность ворона, инвентарь и временный эффект галлюцинации. Класс
 * пока не связан с интерфейсом и не принимает решения за игровой экран.
 *
 * TODO: сверить поля и правила с полной версией концепта, когда она будет
 * доступна в извлекаемом виде, и подключить Player к игровой сессии.
 */
class Player {

    /**
     * Максимальное здоровье игрока.
     * В концепте указано 3–5 сердец на раунд; для начального каркаса
     * выбрано верхнее значение. Позже можно задавать здоровье уровнем,
     * сложностью или параметрами конкретной игровой сессии.
     */
    val maxHealth: Int = DEFAULT_MAX_HEALTH

    /**
     * Текущее здоровье игрока в сердцах.
     * Изменять его следует через takeDamage() и heal(), чтобы значение
     * оставалось в диапазоне от нуля до maxHealth.
     */
    var health: Int = maxHealth
        private set

    /**
     * Есть ли у игрока доступный ворон.
     * Сам концепт в текущем README не описывает эффект и число применений,
     * поэтому это только состояние-заглушка, без придуманного поведения.
     *
     * TODO: уточнить, сопровождает ли ворон игрока постоянно, как помогает
     * и когда его доступность восстанавливается.
     */
    var ravenAvailable: Boolean = true
        private set

    /**
     * Число оставшихся ходов эффекта галлюцинации.
     * По концепту после ложного сморчка интерфейс показывает неверные типы
     * грибов в течение двух ходов. Ноль означает, что эффекта сейчас нет.
     */
    var hallucinationTurnsRemaining: Int = 0
        private set

    /**
     * Инвентарь игрока: соль, синичка, молоко и лупа.
     * Ограничение в три слота уже заложено в PlayerInstruments.
     */
    val instruments = PlayerInstruments()

    /** Игрок проиграл раунд, когда здоровье опустилось до нуля. */
    val isAlive: Boolean
        get() = health > 0

    /**
     * Нанести игроку урон, например от ядовитого гриба.
     * Урон не может быть отрицательным, а здоровье не опустится ниже нуля.
     *
     * TODO: передавать сюда эффекты гриба и подключить звук/вибрацию
     * при укусе мухомора на уровне игровой сессии.
     */
    fun takeDamage(amount: Int) {
        require(amount >= 0) { "Урон не может быть отрицательным" }
        health = (health - amount).coerceAtLeast(0)
    }

    /**
     * Восстановить здоровье, например эффектом фляги молока.
     * Здоровье не может превысить maxHealth.
     *
     * TODO: уточнить, можно ли лечить игрока выше стартового числа сердец
     * конкретного раунда, если оно меньше maxHealth.
     */
    fun heal(amount: Int) {
        require(amount >= 0) { "Лечение не может быть отрицательным" }
        health = (health + amount).coerceAtMost(maxHealth)
    }

    /**
     * Начать или продлить галлюцинацию на два хода.
     * Вызывается игровой логикой, когда игрок съел ложный сморчок.
     */
    fun startHallucination() {
        hallucinationTurnsRemaining = HALLUCINATION_DURATION_TURNS
    }

    /**
     * Уменьшить таймер галлюцинации после завершения хода.
     * TODO: определить, чей именно ход уменьшает таймер, и вызывать это
     * централизованно из контроллера игровой сессии.
     */
    fun advanceTurn() {
        if (hallucinationTurnsRemaining > 0) {
            hallucinationTurnsRemaining--
        }
    }

    /**
     * Использовать помощь ворона.
     *
     * TODO: реализовать эффект и вернуть true, если ворон успешно применён.
     * Пока метод возвращает false и не расходует доступность, потому что
     * действие ворона и правила восстановления ещё не описаны в README.
     */
    fun useRaven(): Boolean {
        // TODO: проверить ravenAvailable, применить эффект ворона и обновить
        // состояние доступности после успешного применения.
        return false
    }

    /**
     * Подготовить игрока к следующему раунду.
     * Стартовое здоровье раунда задаётся явно и должно быть от 3 до 5 сердец.
     *
     * TODO: добавить сюда восстановление ворона и сброс эффектов/инвентаря,
     * когда будут согласованы правила перехода между раундами.
     */
    fun startRound(startingHealth: Int = maxHealth) {
        require(startingHealth in MIN_ROUND_HEALTH..MAX_ROUND_HEALTH) {
            "Здоровье в начале раунда должно быть от $MIN_ROUND_HEALTH до $MAX_ROUND_HEALTH"
        }
        health = startingHealth.coerceAtMost(maxHealth)
        hallucinationTurnsRemaining = 0
    }

    companion object {
        /** Число сердец выбрано как верхняя граница диапазона из концепта. */
        private const val DEFAULT_MAX_HEALTH = 5

        /** Длительность эффекта ложного сморчка из описания концепта. */
        private const val HALLUCINATION_DURATION_TURNS = 2

        private const val MIN_ROUND_HEALTH = 3
        private const val MAX_ROUND_HEALTH = 5
    }
}
